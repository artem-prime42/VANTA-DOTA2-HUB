function getLanguage() {
  if (typeof state !== 'undefined' && state.data?.settings?.appLanguage === 'ru') return 'ru';
  return 'en';
}

function t(key, fallback) {
  const locale = I18N[getLanguage()] || I18N.en;
  const raw = locale[key] || I18N.en[key] || fallback || key;
  return raw;
}

function formatTranslation(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

function setLocalizedText(node, key, values) {
  if (!node) return;
  const value = values ? formatTranslation(t(key), values) : t(key);
  node.textContent = value;
}

function applyDataI18n() {
  if (typeof document === 'undefined') return;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (!key) return;
    const value = t(key);
    if (value) node.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (!key) return;
    const value = t(key);
    if (value) node.placeholder = value;
  });
  document.querySelectorAll('[data-i18n-title]').forEach((node) => {
    const key = node.dataset.i18nTitle;
    if (!key) return;
    const value = t(key);
    if (value) node.title = value;
  });
}

if (typeof MutationObserver !== 'undefined' && typeof document !== 'undefined' && document.body) {
  const i18nObserver = new MutationObserver(() => requestAnimationFrame(applyDataI18n));
  i18nObserver.observe(document.body, { childList: true, subtree: true });
}

if (typeof window !== 'undefined') {
  window.i18n = { I18N, t, getLanguage, applyDataI18n, formatTranslation };
}

if (typeof document !== 'undefined') {
  requestAnimationFrame(applyDataI18n);
}
